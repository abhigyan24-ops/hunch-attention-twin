/**
 * tasks.ts — Thin vscode adapter for VS Code task execution events.
 *
 * Listens to `vscode.tasks.onDidEndTaskProcess` and classifies tasks
 * into categories: 'build' | 'test' | 'lint' | 'run' | 'other'.
 *
 * Privacy rules (HARD):
 *   - Task names are classified to a category bucket; raw names are NOT emitted.
 *   - Only category and exit code are recorded.
 */

import type { Clock } from '../clock.ts';
import type { BreakDetector } from '../aggregate/breaks.ts';
import type { TaskContextTracker } from '../aggregate/taskContext.ts';
import type { Outbox } from '../link/outbox.ts';
import { PrivacyGate } from '../privacy/gate.ts';

export type TaskCategory = 'build' | 'test' | 'lint' | 'run' | 'other';

// Keyword patterns to classify a task by its name/type
const BUILD_KEYWORDS = /\b(build|compile|webpack|esbuild|rollup|tsc|javac|gradle|make|cmake|cargo build|go build|dotnet build)\b/i;
const TEST_KEYWORDS  = /\b(test|jest|mocha|vitest|pytest|unittest|jasmine|karma|rspec|cargo test|go test)\b/i;
const LINT_KEYWORDS  = /\b(lint|eslint|tslint|flake8|pylint|rubocop|checkstyle|golint|clippy|prettier|format)\b/i;
const RUN_KEYWORDS   = /\b(run|start|serve|watch|dev|nodemon|flask|uvicorn|next dev|ng serve)\b/i;

export function classifyTaskName(name: string, taskType?: string): TaskCategory {
  // VS Code exposes a type like 'shell', 'process', 'npm', etc.
  // We inspect the name first; type is a secondary signal.
  if (TEST_KEYWORDS.test(name))  return 'test';
  if (LINT_KEYWORDS.test(name))  return 'lint';
  if (BUILD_KEYWORDS.test(name)) return 'build';
  if (RUN_KEYWORDS.test(name))   return 'run';
  // npm tasks: try to classify from the npm script name
  if (taskType === 'npm' || taskType === 'grunt' || taskType === 'gulp') {
    if (TEST_KEYWORDS.test(name))  return 'test';
    if (BUILD_KEYWORDS.test(name)) return 'build';
    if (LINT_KEYWORDS.test(name))  return 'lint';
  }
  return 'other';
}

export class TasksSensor {
  private disposables: Array<{ dispose: () => void }> = [];
  private clock: Clock;
  private breakDetector: BreakDetector;
  private taskContextTracker: TaskContextTracker;
  private outbox: Outbox;
  private onFlushImmediate: () => void;

  // Callback to emit ed_break immediately when test_ok / build_ok
  private onBreakEmit: (kind: string, confidence: number) => void;

  constructor(
    vscodeApi: any,
    clock: Clock,
    breakDetector: BreakDetector,
    taskContextTracker: TaskContextTracker,
    outbox: Outbox,
    onFlushImmediate: () => void,
    onBreakEmit: (kind: string, confidence: number) => void
  ) {
    this.clock = clock;
    this.breakDetector = breakDetector;
    this.taskContextTracker = taskContextTracker;
    this.outbox = outbox;
    this.onFlushImmediate = onFlushImmediate;
    this.onBreakEmit = onBreakEmit;

    try {
      if (vscodeApi?.tasks?.onDidEndTaskProcess) {
        const sub = vscodeApi.tasks.onDidEndTaskProcess((event: any) => {
          this.handleTaskEnd(event);
        });
        this.disposables.push(sub);
      }
    } catch {
      // Tasks API unavailable — silent no-op
    }
  }

  dispose(): void {
    for (const d of this.disposables) {
      try { d.dispose(); } catch {}
    }
    this.disposables = [];
  }

  // ── Internal ───────────────────────────────────────────────────────────────

  private handleTaskEnd(event: any): void {
    try {
      const name: string = event?.execution?.task?.name ?? '';
      const taskType: string = event?.execution?.task?.type ?? '';
      const exitCode: number = event?.exitCode ?? -1;

      const category = classifyTaskName(name, taskType);

      // 1. Notify TaskContextTracker (for taskType inference)
      this.taskContextTracker.recordTaskEnd(category);

      // 2. Notify BreakDetector (may generate test_ok / build_ok)
      this.breakDetector.onTaskEnd(category, exitCode);

      // 3. Emit ed_task event
      const now = this.clock.now();
      const mono = this.clock.mono();
      const rawEvent = {
        type: 'ed_task',
        ts: now,
        mono,
        taskCategory: category,
        exitCode
      };

      const sanitized = PrivacyGate.sanitize(rawEvent);
      if (sanitized) {
        this.outbox.enqueue(sanitized);

        // Flush immediately for successful test/build completions (natural breaks)
        if (exitCode === 0 && (category === 'test' || category === 'build')) {
          // Drain break events generated by BreakDetector and emit them
          const breaks = this.breakDetector.drainPending();
          for (const brk of breaks) {
            this.onBreakEmit(brk.kind, brk.confidence);
          }
          this.onFlushImmediate();
        }
      }
    } catch {
      // Swallow all errors — never interrupt the user
    }
  }
}
